// lib/search-normalize.ts
//
// 検索キーの機械正規化（docs/frontend-architecture.md §7.2 手順2・§5.4.0）。
// 利用者入力（クエリ）と索引キー生成の双方に「同一関数」を適用し、両者を同じ
// 正規化空間へ畳む。これにより 7.1 の各段（完全一致・読み一致・前方/部分一致）が
// 単純な文字列比較で成立する。
//
// 崩さない前提（§7.0）：
//   - 正規化は検索キー／スラッグに対してのみ行う。画面表示用の正式名称は一切変換しない。
//   - 実行時に「正規化ロジック」は最小限しか持ち込まない（§7.2）。本関数は入力を索引と
//     同じ空間へ寄せるための汎用正規化に限り、ヘボン式変換・名寄せ辞書は持ち込まない。
//   - 機械正規化で吸収しきれない異体字・旧字/新字・通称は、本関数で扱わず
//     名寄せ辞書の例外エントリ（§7.2 手順3・area_code に紐付く）で解決する＝分業を崩さない。

/** ひらがな（ぁ〜ゖ）→カタカナ。かな読みの表記系をカタカナ一系統へ寄せる。 */
function hiraganaToKatakana(s: string): string {
  return s.replace(/[\u3041-\u3096]/g, (c) =>
    String.fromCharCode(c.charCodeAt(0) + 0x60),
  );
}

/**
 * 検索キー正規化。索引生成時・実行時入力の双方で用いる唯一の正規化。
 *
 * 手順（§7.2 手順2 の「全角半角・カナ半角全角・ヶ/ケ・記号ゆれ」の吸収）：
 *   1) NFKC：全角英数記号→半角、半角カナ（ﾎｯｶｲﾄﾞｳ）→全角カナ（ホッカイドウ・濁点結合）、
 *      互換文字の畳み込み。
 *   2) 小文字化：ローマ字読み・英字入力の大小差を吸収（§5.4.0 は小文字 a–z）。
 *   3) ひらがな→カタカナ：かな読みの表記系を一系統へ。
 *   4) 「ヶ/ヵ」→「ケ/カ」、長音符「ー」・中点・各種空白・ハイフン類を除去。
 *
 * 注：カナのウ/オ長音（トウキョウ 等）の単母音化は「ヘボン式ローマ字キー」生成の責務
 *     （§5.4.2）であり、索引生成スクリプト側で行う。本関数は記号としての長音符のみ除去する。
 */
export function normalizeSearchKey(raw: string): string {
  if (!raw) return "";
  let s = raw.normalize("NFKC");
  s = s.toLowerCase();
  s = hiraganaToKatakana(s);
  s = s.replace(/ヶ/g, "ケ").replace(/ヵ/g, "カ");
  // 長音符・中点・各種スペース・ハイフン/ダッシュ類を除去（表記ゆれの吸収）。
  s = s.replace(/[ー・\u3000\s\u002d\u2010-\u2015\u2212]/g, "");
  return s;
}
